export function translate(text: string, language = useAppStore.getState().language): string {
  return language === 'uk' ? (ukrainian[text] ?? text) : text
}
export function useTranslate() {
  const language = useAppStore((s) => s.language)
  return (text: string) => translate(text, language)
}
